#!/usr/bin/env python3
"""Regenerates docs/architecture/metric-names.md from sdk/src/export.cpp and
sdk/src/metrics.cpp, so the published names cannot drift from the code.
robotweax_srt_telemetry_export_tests checks that every name is listed."""
import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parent.parent
export = (root / "sdk/src/export.cpp").read_text()
metrics = (root / "sdk/src/metrics.cpp").read_text()

def joined(text):
    # Concatenate adjacent C string literals.
    return re.sub(r'"\s*\n\s*"', "", text)

export_j = joined(export)
names = re.findall(r'\{"(srt\.[a-z_.]+)",\s*"(srt_[a-z_]+)",\s*"(sender|receiver|connection)",\s*"((?:[^"\\]|\\.)*)"\}',
                   export_j)
counters = re.findall(r'"(srt\.[a-z_.]+)",\s*"(srt_[a-z_]+_total)",\s*"(sender|receiver)",\s*"((?:[^"\\]|\\.)*)"\}',
                      export_j)
catalog = re.findall(r'\{"([a-z_]+)", "([^"]+)", (rate|gauge|ratio), (sender|receiver|both)\}', metrics)
if len(names) != len(catalog) or not counters:
    sys.exit(f"parse error: {len(names)} names, {len(catalog)} catalog entries, {len(counters)} counters")

rows = []
for (otel, prom, scope, help_text), (_, unit, kind, _) in zip(names, catalog):
    stats = "rate, max, p95" if kind == "rate" else "min, max, mean, last, p95"
    rows.append(f"| `{otel}` | `{prom}` | {unit} | {kind} | {stats} | {help_text} |")
counter_rows = [f"| `{o}` | `{p}` | {s} | {h} |" for o, p, s, h in counters]

doc = f"""# Metric names

<!-- Generated by tools/metric_names_doc.py from sdk/src/export.cpp; edit there. -->

Every output (the streaming callbacks, Prometheus, the JSON snapshot, OTLP,
the WebSocket feed and the built-in UI) uses one naming scheme. Its version is
`ROBOTWEAX_SRT_TELEMETRY_METRIC_SCHEMA_VERSION` (currently 1), exported as
`srt_telemetry_schema_info{{version="1"}}` and as `metric_schema` in the JSON
snapshot. A released name never changes meaning. A change gets a new name and
a new schema version.

## Conventions

- **OpenTelemetry style** (`srt.<scope>.<name>`): used by the JSON snapshot,
  OTLP and the UI. The unit is a separate attribute, in UCUM. Ratios of two
  quantities of the same kind are named `*.utilization` or carry a
  descriptive name, with unit `1`.
- **Prometheus** (`srt_<scope>_<name>_<unit>`): `_total` for counters.
  - Bit rates are exported in bits per second, deliberately: SRT settings,
    encoders and operators all work in bit/s.
  - Byte counters count wire bytes, including IP/UDP/SRT headers.
- **Scope:** `sender`, `receiver` or `connection` (both roles). A source
  exports the metrics of its own role and of the connection; a source of
  unknown role exports all of them.
- **Missing values:** a metric that is unavailable for a source is left out.
  It is never exported as zero.
- **C names:** `robotweax_srt_telemetry_metric_otel_name()`,
  `_metric_prometheus_name()` and `_metric_scope()` return the names for each
  `robotweax_srt_telemetry_metric`. Streaming callbacks use them to label
  their own outputs.

## Window metrics

These are exported from the latest closed window: 10 s by default, any
configured length on request.
- **Rates** carry the exact window rate (window total ÷ covered time) and the
  peak 100 ms rate.
- **Gauges and ratios** carry min, max, mean and last.
- **p95** is present where it is computed: by default for bitrates, RTT,
  buffers and recovery headroom.

In Prometheus the statistic is the `stat` label, and **every query must select
one** (`{{stat="rate"}}`, `{{stat="min"}}`…). Summing across `stat` adds
unrelated values. For rates, `max` and `p95` describe 100 ms samples; for
gauges they describe the sampled values. In JSON each metric is an object with
one key per statistic, and rates also have `total`.

| OpenTelemetry name | Prometheus family | Unit | Kind | Statistics | Meaning |
| --- | --- | --- | --- | --- | --- |
""" + "\n".join(rows) + """

`srt.connection.link_capacity_estimate` is SRT's packet-pair estimate. Only
Haivision SRT provides it. On a healthy path it follows the arrival rate, so
it is not a measure of spare capacity (see the
[fault lab](../qualification/fault-lab.md)).

## Lifetime counters

Totals since the connection started, read from the latest sample. A new
connection starts at zero; Prometheus treats that as a counter reset. Counters
are printed as exact integers. Use them with `rate()` and `increase()` over
any range.

| OpenTelemetry name | Prometheus family | Scope | Meaning |
| --- | --- | --- | --- |
""" + "\n".join(counter_rows) + """

## Health

| Prometheus family | OTLP (unit) | JSON (`health`) | Meaning |
| --- | --- | --- | --- |
| `srt_health_verdict` | `srt.health.verdict` ({verdict}) | `verdict` | 0 unknown, 1 ok, 2 watch, 3 at risk, 4 failing |
| `srt_health_info{verdict,reason,knob,direction}` | `srt.health.info` ({info}) | `verdict`, `reason`, `knob`, `direction` | Current verdict with its reason and suggested knob (value 1) |
| `srt_health_suggested_value{knob}` | `srt.health.suggested_value` ({value}) | `suggested_value` (null without one) | Value for the knob in its unit: s, bit/s, bytes/s or percent |
| `srt_health_indicator_state{indicator}` | `srt.health.indicator.state` ({state}) | `indicators[].state` | Each indicator after hysteresis |
| `srt_health_indicator_value{indicator}` | `srt.health.indicator.value` (1) | `indicators[].value` | Each indicator's value (null when unavailable) |
| — | — | `primary_indicator`, `missing_metrics`, `verdict_age_seconds` | Indicator behind the verdict; metrics a verdict needed but did not get; how long the verdict had held at the latest sample |
| `srt_health_path_verdict` | `srt.health.path_verdict` ({verdict}) | `uncapped_verdict` (with `group_member`) | A connection-group path's own grade; its `verdict` is capped at Watch while another path is usable (`capped`) |
| `srt_group_usable_paths` | `srt.group.usable_paths` ({path}) | `group.usable_paths` | A connection group's own row: paths that can carry the stream now |
| `srt_group_expected_paths` | `srt.group.expected_paths` ({path}) | `group.expected_paths` | Paths the group is meant to have: set by the host, else the most seen usable at once |

Reason, knob and indicator names are those of
`robotweax_srt_telemetry_health_*_name()`
(see [Health engine](health-engine.md)).

## Source and window

| Prometheus family | OTLP (unit) | JSON | Meaning |
| --- | --- | --- | --- |
| `srt_source_up` | `srt.source.up` ({up}) | `up` | 1 while statistics reads succeed |
| — | — | `connection` | `connected`, `connecting`, `lost` or `unreported` (from the health context) |
| `srt_window_seconds` | `srt.window.length` (s) | `window_seconds` (top level) | Length of the exported window |
| `srt_window_samples` | `srt.window.samples` ({sample}) | `window.samples` | Samples in it |
| `srt_window_quality{flag}` | `srt.window.quality` ({flag}) | `window.quality` | `partial`, `sampling_gap`, `clock_step`, `counter_reset`, `baseline`, `source_error` |

While a source's statistics read fails (`srt_source_up` 0), its counters and
`latest` metrics keep the last good values. Its windows carry the
`source_error` flag, and the health verdict says why.

If no newer window has arrived for two more window lengths (the sampler
stopped ticking), the window is left out as stale. This is judged on the
steady clock, so it does not depend on host timestamps or clock steps.

## OTLP

The OTLP renderer (`ROBOTWEAX_SRT_TELEMETRY_RENDER_OTLP_JSON`, sent by the
[OTLP exporter](otlp.md)) uses the OpenTelemetry names above with the same
attributes as the Prometheus labels: window metrics are gauges with a `stat`
attribute, counters are cumulative monotonic sums, and the health, source and
window families are gauges.

A Collector that re-exports to Prometheus derives names from the OpenTelemetry
name and unit. Window metrics and counters get other names than the native
families (`srt.receiver.unique_received.bitrate` becomes
`srt_receiver_unique_received_bitrate_bit_per_second`), as does
`srt.window.length`; the health and source families keep theirs, because
their units are annotations. Resource attributes become labels
(`service_name`, `service_instance_id`, …), and `job` and `instance` name the
Collector, not the process. The [dashboards](alerting.md) use the native
names: scrape the embedded server for them, and use OTLP for OpenTelemetry
backends. The stream alerts work on both paths.

## Labels

Every Prometheus series carries `source_id`, `role` and the source's host
labels. A host key may collide with an exporter label: `source_id`, `role`,
`stat`, `flag`, `indicator`, `verdict`, `reason`, `knob`, `direction`, `job`,
`instance`, or any key starting with `__`. Such a key gets `host_` prefixes
until it is unique among the series' labels. For example, `role` becomes
`host_role`, or `host_host_role` when the host also set `host_role`. In
JSON, host labels appear unchanged under `labels`.

## JSON snapshot

`schema` is `srt-telemetry.snapshot.v1`. Top level: `metric_schema`,
`generated_unix_nano` and `generated_unix_ms` (time of the latest tick),
`window_seconds`, `observer`, `sources`. `observer` is `null` unless the host
exports it (`sampler_set_observer_v1`, or `embed_export_observer_v1`), else
`{{node, instance}}`, each `null` when unknown. Each source has:

- `id`, `role`, `labels`, `up`, `connection`;
- `connection_seq` (grows by one with each new connection of the source),
  `connected_at_unix_ms` (the current connection's start from the provider's
  connection age, while connected) and `session_ref` (the host's session
  reference), each `null` when unknown (`sampler_set_source_identity_v1`);
- `window` (when a window has closed): `start_unix_nano`, `end_unix_nano`,
  `start_unix_ms`, `end_unix_ms`, `samples`, `quality`, `metrics`;
- `latest` (the latest sample): `observed_unix_nano`, `observed_unix_ms`,
  `metrics`;
- `counters`;
- `health` (when health is enabled).

Nanosecond timestamps exceed 2^53, so JavaScript clients should use the `_ms`
fields.

## Size and cost

Two sources (one sender, one receiver) render to about 25 KB of Prometheus
text, roughly 75 series per source. For large fleets, the flags
`RENDER_NO_COUNTERS` and `RENDER_NO_INDICATORS` trim the output. Rendering
copies about 5 KB per source under the sampler lock, and the buffer variant
renders twice when it has to report the size. Phase 4 measures scrape cost at
1,000 sockets.

## Tests

- `robotweax_srt_telemetry_export_tests`:
  - names: unique, scoped and unit-suffixed, and all listed in this document;
  - Prometheus output parsed line by line: syntax, one HELP and TYPE per
    family before its samples, no duplicate series;
  - label escaping, and renaming of reserved and colliding keys;
  - role scoping, exact window rates, counters exact above 1e11, health
    series and flags;
  - health disabled, stale windows, no sources;
  - the JSON snapshot checked by a strict parser;
  - the buffer variant (size query, too small, exact) and a writer that calls
    the sampler.
- `robotweax_srt_telemetry_public_srt_sampler_test` (live, each provider):
  both formats render the sender and receiver of a real SRT stream.
"""
(root / "docs/architecture/metric-names.md").write_text(doc)
